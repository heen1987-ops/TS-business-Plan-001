def start(title):
    global active
    active=[]
    d=helper['setup'](title)
    d.styles['Normal'].font.size=Pt(10.5)
    d.styles['Normal'].paragraph_format.line_spacing=1.14
    d.styles['Normal'].paragraph_format.space_after=Pt(5)
    for name,size in [('Title',23),('Heading 1',16),('Heading 2',12.5)]:
        d.styles[name].font.size=Pt(size)
        d.styles[name].paragraph_format.space_before=Pt(0 if name=='Title' else 9)
        d.styles[name].paragraph_format.space_after=Pt(6)
    d.styles['List Bullet'].font.size=Pt(10.5)
    d.styles['List Bullet'].paragraph_format.line_spacing=1.14
    d.styles['List Bullet'].paragraph_format.space_after=Pt(4)
    h(d,title,0)
    p(d,'2026년 9월 11일  |  v0.1  |  기관 검토용 설계안')
    return d

def p(d,text,bold=False,style=None):
    active.append(text)
    x=d.add_paragraph(style=style)
    helper['inline'](x,text,bold=bold)
    return x

def h(d,text,level=1,new=False):
    active.append(text)
    x=d.add_paragraph(text,style='Title' if level==0 else 'Heading '+str(level))
    if new:x.paragraph_format.page_break_before=True
    return x

def t(d,headers,rows,widths):
    active.extend(headers)
    for row in rows:active.extend(row)
    helper['widths']=lambda _:widths
    result=helper['table'](d,[headers]+rows)
    gap=d.paragraphs[-1]
    gap.paragraph_format.line_spacing=Pt(2)
    gap.paragraph_format.space_after=Pt(2)
    return result

def bullet(d,text):return p(d,text,style='List Bullet')
def save(d,name,expected_pages):
    d.save(OUT/name)
    logs[name]={'text_units':active.copy(),'expected_pages':expected_pages}

