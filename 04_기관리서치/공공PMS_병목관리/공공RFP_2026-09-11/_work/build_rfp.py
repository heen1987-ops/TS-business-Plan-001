def compact_ids(ids):
    groups=collections.defaultdict(list)
    for id in ids:
        mt=re.fullmatch(r'([A-Z]+)-(\d+)',id)
        if mt:groups[mt[1]].append(int(mt[2]))
    result=[]
    for prefix,values in groups.items():
        values=sorted(set(values));start=prev=values[0]
        for n in values[1:]+[None]:
            if n is not None and n==prev+1:prev=n;continue
            result.append(f'{prefix}-{start:03d}'+(f'~{prev:03d}' if prev!=start else ''))
            start=prev=n
    return ', '.join(result)
