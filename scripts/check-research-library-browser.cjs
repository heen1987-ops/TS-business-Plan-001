  check('직접주소 위치·고정헤더 회피',await page.locator('#news-N06').evaluate(el=>el.getBoundingClientRect().top>=document.querySelector('.ts-location').getBoundingClientRect().bottom-2&&el.getBoundingClientRect().top<innerHeight));
