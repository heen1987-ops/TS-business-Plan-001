const fs=require('node:fs'),assert=require('node:assert/strict');
const library=require('../src/research-library.cjs'),research=require('../src/association-research.json'),manifest=require('../src/department-documents.json'),nav=require('../src/navigation.cjs'),routes=require('../site-routes.json').routes;
let checks=0;const check=(value,label)=>{assert(value,label);checks++};
const read=file=>fs.readFileSync(file,'utf8');
check(routes.includes('research-library.html'),'자료실 React 경로 등록');
check(nav.locate('research-library.html')?.menuId==='resources','자료실 상위 메뉴 소속');
check(nav.locate('research-library.html#news-N06')?.id==='research-library','자료실 직접 앵커 위치 인식');
check(fs.existsSync('dist/research-library.html'),'자료실 빌드 산출물');
check(!read('src/App.jsx').includes('AssociationUpdate'),'홈 조사 배너 제거');
check(!read('src/DocumentReader.jsx').includes('CommonFinding47'),'기관 소개의 조사 안내 별도 강조 제거');
check(read('src/Revision47.jsx').includes('CommonFinding47'),'제안·근거의 공통 맥락 보존');
check(read('src/Associations.jsx').includes("id={'news-'+c.id}"),'기존 뉴스 직접 주소 보존');
check(read('src/Associations.jsx').includes("id={'issue-'+i.id}"),'기존 공개 쟁점 직접 주소 보존');
check(read('src/ResearchLibrary.jsx').includes('proposalBase="associations.html"'),'다른 페이지의 조사 후보 연결');
check(library.categories.length===4,'4개 자료 분류');
check(library.categories[0].count===research.news_research.cases.length,'뉴스 원장 개수 일치');
check(library.categories[1].count===research.issues.length,'공개 쟁점 원장 개수 일치');
check(library.categories[2].count===null,'공식 자료 미집계 수치 생성 금지');
check(library.categories[3].count===manifest.departments.reduce((n,d)=>n+d.documents.length,0),'한글 파일 원장 개수 일치');
for(const link of [...library.officialLinks,...library.downloads])check(fs.existsSync('dist/'+link.to.split(/[?#]/)[0]),'자료 연결 '+link.to);
check(research.issues.every(i=>/^https:\/\//.test(i.source_url)&&i.source_title&&i.evidence_level),'공개 쟁점의 출처·확인 상태');
const archived=JSON.parse(read('dist/downloads/association-research.json'));
assert.deepEqual(archived,research,'조사 원장·공개 다운로드 무변경 일치');checks++;
console.log(JSON.stringify({result:'통과',checks,groups:library.categories.length,news:research.news_research.cases.length,issues:research.issues.length}));
